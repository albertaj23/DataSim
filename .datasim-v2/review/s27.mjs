import {launch,BASE,sleep,idle} from './lib.mjs';
import fs from 'node:fs';
const pid=fs.readFileSync('.datasim-v2/review/pid2.txt','utf8');
const A='http://127.0.0.1:4000/api';
await idle();
const {page,shot,done,ctx}=await launch();
const T=Date.now(); const t=()=>((Date.now()-T)/1000).toFixed(1);
await page.goto(BASE+'p/'+pid); await sleep(2000);
await page.locator('.react-flow__pane').click({position:{x:100,y:100}});
await page.keyboard.press('Control+Enter'); console.log(t(),'ctrl+enter pressed'); await sleep(2500);
console.log(t(),'phase:',await page.getByTestId('phase-text').innerText().catch(()=>'NONE'));
const p2=await ctx.newPage(); await p2.goto(BASE+'p/'+pid); await sleep(2000);
console.log(t(),'p2 phase',await p2.getByTestId('phase-text').innerText().catch(()=>'NONE'),'stop',await p2.getByTestId('stop-run').count());
await p2.screenshot({path:'.datasim-v2/review/screens/161-second-tab-live.png'});
const r=await fetch(A+`/projects/${pid}/runs`,{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({kind:'LOAD'})}); console.log(t(),'API 2nd run on SAME project',r.status,await r.text());
await p2.getByRole('button',{name:'Run',exact:true}).click().catch(e=>console.log('run btn:',e.message.slice(0,60))); await sleep(1500);
console.log(t(),'p2 run click toasts:',await p2.locator('[role=alert],[role=status]').allInnerTexts());
await p2.screenshot({path:'.datasim-v2/review/screens/162-second-run-active.png'});
console.log(t(),'stop on page1',await page.getByTestId('stop-run').count());
await page.getByTestId('stop-run').click(); await sleep(3500); await shot('163-after-cancel');
console.log(t(),'after cancel:',await page.getByTestId('bottom-panel').innerText().then(x=>x.slice(0,500)));
console.log('health',await (await fetch(A+'/health')).text());
console.log('toasts',await page.locator('[role=alert],[role=status]').allInnerTexts());
await done('s27-run-controls');
