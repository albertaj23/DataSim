import { chromium } from '@playwright/test';
const A = 'http://127.0.0.1:4000/api', W = 'http://127.0.0.1:5173/DataSim/';
const pid = '93cb667c-3a7a-42ec-81bb-471670499035';
const runs = await (await fetch(`${A}/runs?projectId=${pid}`)).json();
const by = (k, s, rev) => runs.find((r) => r.kind === k && (!s || r.strategy === s) && (!rev || r.revisionNo === rev));
const naive = by('LOAD', 'naive'), atomic = by('LOAD', 'atomic', 1), cap = by('CAPACITY');
const out = 'docs/pdf';
const b = await chromium.launch(); const ctx = await b.newContext({ viewport: { width: 1440, height: 900 }, colorScheme: 'dark' });
const p = await ctx.newPage();
const shot = async (n) => { await p.waitForTimeout(1200); await p.screenshot({ path: `${out}/${n}.png` }); };
await p.goto(W); await p.waitForSelector('[data-testid="project-row"]'); await shot('projects');
await p.goto(`${W}p/${pid}`); await p.waitForSelector('[data-testid="node-users"]'); await shot('studio-idle');
await p.goto(`${W}p/${pid}?run=${naive.runId}`); await p.waitForSelector('[data-testid="verdict"]', { timeout: 30000 }).catch(() => {}); await shot('studio-naive');
await p.getByRole('tab', { name: /Findings/ }).click().catch(() => {}); await shot('studio-findings');
await p.dblclick('[data-testid="node-mysql"]'); await shot('schema-designer');
await p.keyboard.press('Escape');
await p.dblclick('[data-testid="node-users"]'); await shot('workload-editor'); await p.keyboard.press('Escape');
await p.goto(`${W}runs/${naive.runId}`); await p.waitForSelector('[data-testid="kpi-strip"]'); await shot('report-naive');
await p.evaluate(() => window.scrollTo(0, 900)); await shot('report-naive-2');
await p.goto(`${W}runs/${cap.runId}`); await p.waitForSelector('[data-testid="capacity-sentence"]'); await shot('report-capacity');
await p.evaluate(() => window.scrollTo(0, 500)); await shot('report-capacity-2');
await p.goto(`${W}compare?ids=${naive.runId},${atomic.runId}`); await p.waitForTimeout(1500); await shot('compare');
await p.goto(`${W}runs`); await shot('runs');
await p.goto(`${W}lab`); await shot('lab');
await p.goto(`${W}stepper`); await shot('stepper');
await b.close(); console.log('ok');
